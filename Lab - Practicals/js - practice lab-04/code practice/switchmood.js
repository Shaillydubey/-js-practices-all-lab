let mood = "happy";

switch (mood) {
    case "happy":
        console.log("You are happy ");
        break;

    case "sad":
        console.log("You are sad ");
        break;

    case "angry":
        console.log("You are angry ");
        break;

    case "excited":
        console.log("You are excited ");
        break;

    default:
        console.log("Unknown mood");
}